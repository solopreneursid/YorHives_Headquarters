import assert from 'node:assert/strict';
import {assessFreeToolsEvidence,loadFreeToolsOperations,readPublicEvidence} from '../src/free-tools-operations.mjs';
const NOW=Date.parse('2026-11-21T10:00:00Z');
const url='https://github.com/solopreneursid/YorpHives_Website';
const goodRun={id:777,status:'completed',conclusion:'success',updated_at:'2026-11-21T09:00:00Z',html_url:url+'/actions/runs/777'};
const failedRun={...goodRun,conclusion:'failure'};
const open={number:19,title:'YorpHives Free Tools watchdog failure',state:'open',updated_at:'2026-11-21T09:05:00Z',html_url:url+'/issues/19'};
const seo={number:20,title:'YorpHives Free Tools SEO review',state:'open',updated_at:'2026-11-21T09:05:00Z',html_url:url+'/issues/20'};
let x=assessFreeToolsEvidence({runs:{workflow_runs:[goodRun]},issues:[],now:NOW});
assert.equal(x.status,'healthy');assert.equal(x.evidenceVerified,true);assert.equal(x.summary.critical,0);
x=assessFreeToolsEvidence({runs:{workflow_runs:[failedRun]},issues:[open,seo],now:NOW});
assert.equal(x.status,'attention');assert.equal(x.summary.critical,1);assert.equal(x.summary.improvements,1);
assert.equal(x.incidents[0].evidenceUrl,url+'/issues/19');
x=assessFreeToolsEvidence({runs:{workflow_runs:[{...goodRun,updated_at:'2026-11-15T09:00:00Z'}]},issues:[],now:NOW});
assert.equal(x.status,'unverified');assert.equal(x.evidenceVerified,false);
x=assessFreeToolsEvidence({runs:null,issues:null,now:NOW});assert.equal(x.status,'unverified');
const fakeFetch=async address=>new Response(JSON.stringify(address.includes('/runs?')?{workflow_runs:[goodRun]}:[seo]),{headers:{'content-type':'application/json'}});
x=await loadFreeToolsOperations({fetcher:fakeFetch,now:()=>NOW});
assert.equal(x.summary.improvements,1);assert.equal(x.status,'healthy');
await assert.rejects(()=>readPublicEvidence('https://example.org/private',{fetcher:fakeFetch}),/Unexpected/);
const large=async()=>new Response('x'.repeat(66000),{headers:{'content-type':'application/json'}});
await assert.rejects(()=>readPublicEvidence('https://api.github.com/repos/solopreneursid/YorpHives_Website/issues',{fetcher:large}),/oversized/);
console.log('PASS Free Tools HQ read-only evidence, stale and incident classification');
